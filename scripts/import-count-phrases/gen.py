import json, sys
d = json.load(open(sys.argv[1]))
ORDER = ["zero","one","two","few","many","other"]
def q(s): return json.dumps(s, ensure_ascii=False)
HDR = "ETSY plural pass (24 Oct 2026): every counted Etsy / held-order / import sentence, one template per plural\nform, generated from one table (same text on web, iOS/macOS and Android). No new meaning: the 'other' forms are\nthe sentences these screens already showed; the other forms are the same sentence in the right grammatical number."
# TS
ts = ["// " + l for l in HDR.split("\n")] + ["// GENERATED by scripts/import-count-phrases/gen.py from scripts/import-count-phrases/phrases.json — edit the table, not this file.", "",
 "export type StudioImportCountPhrase =", "  " + "\n  | ".join(q(k) for k in d) + ";", "",
 "export const IMPORT_COUNT_PHRASE_FORMS: Record<StudioImportCountPhrase, Record<string, Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }>> = {"]
for i,(k,langs) in enumerate(d.items()):
    ts.append(f"  {q(k)}: {{")
    for j,(l,forms) in enumerate(langs.items()):
        body = ", ".join(f"{c}: {q(forms[c])}" for c in ORDER if c in forms)
        ts.append(f"    {q(l)}: {{ {body} }}" + ("," if j < len(langs)-1 else ""))
    ts.append("  }" + ("," if i < len(d)-1 else ""))
ts.append("};"); ts.append("")
open(sys.argv[2],"w").write("\n".join(ts))
# Swift
sw = ["import Foundation", ""] + ["// " + l for l in HDR.split("\n")] + ["// GENERATED from studioflow-web scripts/import-count-phrases/phrases.json (same table as the web's lib/studioflow/importCountPhrases.ts).",
 "// Read through studioCountLabel(_:_:lang:) — e.g. studioCountLabel(1, \"ordersImported\", lang: lang) → \"1 order imported\".", "",
 "let studioImportCountForms: [String: [String: [String: String]]] = ["]
for i,(k,langs) in enumerate(d.items()):
    sw.append(f"    {q(k)}: [")
    for j,(l,forms) in enumerate(langs.items()):
        body = ", ".join(f"{q(c)}: {q(forms[c])}" for c in ORDER if c in forms)
        sw.append(f"        {q(l)}: [{body}]" + ("," if j < len(langs)-1 else ""))
    sw.append("    ]" + ("," if i < len(d)-1 else ""))
sw.append("]"); sw.append("")
open(sys.argv[3],"w").write("\n".join(sw))
# Kotlin
kt = ["package uk.co.eggcraft.studioflow.language", ""] + ["// " + l for l in HDR.split("\n")] + ["// GENERATED from studioflow-web scripts/import-count-phrases/phrases.json (same table as the web's lib/studioflow/importCountPhrases.ts).",
 "// Read through studioCountLabel(count, \"ordersImported\", lang).", "",
 "internal val IMPORT_COUNT_FORMS: Map<String, Map<String, Map<String, String>>> = mapOf("]
for i,(k,langs) in enumerate(d.items()):
    kt.append(f"    {q(k)} to mapOf(")
    for j,(l,forms) in enumerate(langs.items()):
        body = ", ".join(f"{q(c)} to {q(forms[c])}" for c in ORDER if c in forms)
        kt.append(f"        {q(l)} to mapOf({body})" + ("," if j < len(langs)-1 else ""))
    kt.append("    )" + ("," if i < len(d)-1 else ""))
kt.append(")"); kt.append("")
open(sys.argv[4],"w").write("\n".join(kt).replace("$", "\\$"))
